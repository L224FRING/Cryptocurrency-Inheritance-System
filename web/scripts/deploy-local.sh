#!/usr/bin/env bash
# Deploy VDFVerifier + FROSTVerifier + InheritanceVault to local Anvil and write
# the addresses into web/.env.local so the Next.js app can find them.
#
# Usage:
#   web/scripts/deploy-local.sh                 # uses http://127.0.0.1:8545
#   RPC_URL=http://127.0.0.1:9545 web/scripts/deploy-local.sh
#
# Start Anvil first: anvil
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WEB_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$WEB_DIR/.." && pwd)"
ENV_FILE="$WEB_DIR/.env.local"
RPC_URL="${RPC_URL:-http://127.0.0.1:8545}"

cd "$REPO_ROOT"

if ! command -v forge >/dev/null 2>&1; then
  echo "error: forge is not installed (https://getfoundry.sh)" >&2
  exit 1
fi

if ! cast chain-id --rpc-url "$RPC_URL" >/dev/null 2>&1; then
  echo "error: no JSON-RPC node at $RPC_URL" >&2
  echo "       start one with: anvil" >&2
  exit 1
fi

CHAIN_ID="$(cast chain-id --rpc-url "$RPC_URL")"
if [ "$CHAIN_ID" != "31337" ]; then
  echo "warning: chain id is $CHAIN_ID, not 31337; /api/dev/mine will be disabled" >&2
fi

echo "Deploying to $RPC_URL (chain $CHAIN_ID)…"
OUTPUT="$(forge script script/DeployFull.s.sol \
  --rpc-url "$RPC_URL" \
  --broadcast \
  --color never 2>&1)" || {
  echo "$OUTPUT" >&2
  echo "error: forge script failed" >&2
  exit 1
}

# Console logs look like: "VDFVerifier 0x1234…". Take the last occurrence of
# each label so replayed simulation logs cannot shadow the broadcast result.
extract() {
  local label="$1"
  printf '%s\n' "$OUTPUT" \
    | sed -E 's/\x1b\[[0-9;]*[A-Za-z]//g' \
    | grep -Eo "${label} 0x[0-9a-fA-F]{40}" \
    | tail -n 1 \
    | awk '{print $2}'
}

VDF_ADDRESS="$(extract VDFVerifier || true)"
FROST_ADDRESS="$(extract FROSTVerifier || true)"
VAULT_ADDRESS="$(extract InheritanceVault || true)"

if [ -z "$VDF_ADDRESS" ] || [ -z "$FROST_ADDRESS" ] || [ -z "$VAULT_ADDRESS" ]; then
  echo "$OUTPUT" >&2
  echo "error: could not parse deployed addresses from forge output" >&2
  echo "       inspect broadcast/DeployFull.s.sol/$CHAIN_ID/run-latest.json" >&2
  exit 1
fi

cat >"$ENV_FILE" <<EOF
# Generated by web/scripts/deploy-local.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
NEXT_PUBLIC_RPC_URL=$RPC_URL
NEXT_PUBLIC_CHAIN_ID=$CHAIN_ID
NEXT_PUBLIC_VAULT_ADDRESS=$VAULT_ADDRESS
NEXT_PUBLIC_VDF_ADDRESS=$VDF_ADDRESS
NEXT_PUBLIC_FROST_ADDRESS=$FROST_ADDRESS

# Local demo only: allow /api/dev/mine to advance Anvil.
ALLOW_DEV_MINE=true
EOF

# A redeploy starts from empty contracts, so old shares no longer match the
# new verifier. Remove them and re-run the DKG ceremony from the owner page.
rm -rf "$WEB_DIR/.frost"

echo
echo "Wrote $ENV_FILE"
echo "  Vault            $VAULT_ADDRESS"
echo "  VDFVerifier      $VDF_ADDRESS"
echo "  FROSTVerifier    $FROST_ADDRESS"
echo
echo "Next: restart 'pnpm dev' in web/ (env vars load at boot), then run the"
echo "DKG ceremony on /owner and install the group key."
